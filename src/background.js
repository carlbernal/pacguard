// PacGuard Background Service Worker (Manifest V3)
// Hybrid PAC (chrome.proxy) + DeclarativeNetRequest + WebNavigation

const DEFAULT_SHORTCUTS_TEXT = `# Line 1: go/ link slug
# Line 2: Target website URL

wiki
wikipedia.org

gh
github.com

mail
mail.google.com
`;

const DEFAULT_BLOCKLIST_TEXT = `# One domain per line (blocks domain & all subdomains)
reddit.com
twitter.com
x.com
`;

const DEFAULT_SHORTCUTS = {
  wiki: "https://wikipedia.org",
  gh: "https://github.com",
  mail: "https://mail.google.com",
};

const DEFAULT_BLOCKLIST = ["reddit.com", "twitter.com", "x.com"];

function normalizeDomain(input) {
  return input
    .trim()
    .toLowerCase()
    .replace(/^https?:\/\//, "")
    .replace(/^www\./, "")
    .split("/")[0];
}

function normalizeTargetUrl(input) {
  const clean = input.trim();
  return /^https?:\/\//i.test(clean) ? clean : `https://${clean}`;
}

function escapeRegex(str) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Generates the PAC (Proxy Auto-Config) script string.
 * - Blocked domains (and all subdomains) are routed to a dead local proxy sinkhole
 *   so non-HTTP/WebSocket/subresource requests are severed at the network layer.
 * - `go` shortlink host and normal traffic return DIRECT.
 */
function generatePacScript(blocklist, shortcuts) {
  const cleanBlocked = (blocklist || []).map(normalizeDomain).filter(Boolean);
  const shortcutSlugs = Object.keys(shortcuts || {});

  return `// Auto-generated by PacGuard
// Active go/ links: ${shortcutSlugs.map((s) => "go/" + s).join(", ") || "none"}
var BLOCKED_DOMAINS = ${JSON.stringify(cleanBlocked, null, 2)};

function FindProxyForURL(url, host) {
  host = host.toLowerCase();

  // 1. Blocklist enforcement (exact host + all subdomains)
  for (var i = 0; i < BLOCKED_DOMAINS.length; i++) {
    var blocked = BLOCKED_DOMAINS[i];
    if (host === blocked || dnsDomainIs(host, "." + blocked)) {
      return "PROXY 127.0.0.1:65535";
    }
  }

  // 2. Allow shortlink host ("go") to resolve directly for extension redirect
  if (host === "go" || host === "go.") {
    return "DIRECT";
  }

  return "DIRECT";
}`;
}

/**
 * Synchronizes both the Chrome PAC script and DeclarativeNetRequest rules
 * whenever `shortcuts` or `blocklist` changes in storage.
 * Uses a promise queue so concurrent calls (e.g. onInstalled + storage.onChanged)
 * never race on updateDynamicRules rule IDs.
 */
let syncQueue = Promise.resolve();

function syncControlPlane() {
  syncQueue = syncQueue.then(runSyncControlPlane).catch((err) => {
    console.error("PacGuard syncControlPlane error:", err);
  });
  return syncQueue;
}

async function runSyncControlPlane() {
  const data = await chrome.storage.local.get(["shortcuts", "blocklist"]);
  const shortcuts = data.shortcuts || DEFAULT_SHORTCUTS;
  const blocklist = data.blocklist || DEFAULT_BLOCKLIST;

  // 1. Apply PAC Script via chrome.proxy.settings
  const pacScript = generatePacScript(blocklist, shortcuts);
  await chrome.proxy.settings.set({
    value: {
      mode: "pac_script",
      pacScript: {
        data: pacScript,
        mandatory: false,
      },
    },
    scope: "regular",
  });

  // 2. Rebuild DeclarativeNetRequest rules for instant HTTP redirects & Block Page UI
  const addRules = [];
  let ruleId = 1;

  // A. Shortlink rules: http(s)://go/<slug> -> target URL
  for (const [slug, rawTarget] of Object.entries(shortcuts)) {
    const cleanSlug = slug.trim().replace(/^go\//i, "").replace(/^\/+|\/+$/g, "");
    if (!cleanSlug) continue;

    const targetUrl = normalizeTargetUrl(rawTarget);
    const targetBase = targetUrl.replace(/\/+$/, "");

    // Exact match: http(s)://go/<slug>
    addRules.push({
      id: ruleId++,
      priority: 100,
      action: {
        type: "redirect",
        redirect: { url: targetUrl },
      },
      condition: {
        regexFilter: `^https?://go\\.?/${escapeRegex(cleanSlug)}/?$`,
        resourceTypes: ["main_frame"],
      },
    });

    // Subpath forwarding: http(s)://go/<slug>/<rest> -> targetBase/<rest>
    addRules.push({
      id: ruleId++,
      priority: 99,
      action: {
        type: "redirect",
        redirect: { regexSubstitution: `${targetBase}/\\1` },
      },
      condition: {
        regexFilter: `^https?://go\\.?/${escapeRegex(cleanSlug)}/(.+)$`,
        resourceTypes: ["main_frame"],
      },
    });
  }

  // B. Blocklist rules: redirect main_frame navigations to blocked.html warning page
  const blockedPageBase = chrome.runtime.getURL("blocked.html");
  for (const domain of blocklist) {
    const cleanDomain = normalizeDomain(domain);
    if (!cleanDomain) continue;

    addRules.push({
      id: ruleId++,
      priority: 200,
      action: {
        type: "redirect",
        redirect: {
          regexSubstitution: `${blockedPageBase}?domain=${encodeURIComponent(cleanDomain)}&url=\\0`,
        },
      },
      condition: {
        regexFilter: `^https?://([a-z0-9-]+\\.)*${escapeRegex(cleanDomain)}([:/].*|$)`,
        resourceTypes: ["main_frame"],
      },
    });
  }

  // Fetch existing rule IDs immediately before updating and merge with new IDs
  const existingRules = await chrome.declarativeNetRequest.getDynamicRules();
  const removeRuleIds = Array.from(
    new Set([...existingRules.map((r) => r.id), ...addRules.map((r) => r.id)])
  );

  await chrome.declarativeNetRequest.updateDynamicRules({
    removeRuleIds,
    addRules,
  });
}

/**
 * Resolves `go/<slug>` even when typed directly into Chrome's address bar
 * without `http://` (where Chrome initially treats `go/wiki` as a search query).
 */
function resolveGoNavigation(urlStr, shortcuts) {
  try {
    const u = new URL(urlStr);

    // Direct navigation to http://go/<slug>
    if (u.hostname === "go" || u.hostname === "go.") {
      const parts = u.pathname.replace(/^\/+/, "").split("/");
      const slug = parts[0];
      const rest = parts.slice(1).join("/");
      if (slug && shortcuts[slug]) {
        const base = normalizeTargetUrl(shortcuts[slug]);
        return rest
          ? `${base.replace(/\/+$/, "")}/${rest}${u.search}${u.hash}`
          : `${base}${u.search}${u.hash}`;
      }
    }

    // Address bar search fallback when user types `go/wiki` without `http://`
    const query =
      u.searchParams.get("q") ||
      u.searchParams.get("query") ||
      u.searchParams.get("p");
    if (query && /^go\/[a-zA-Z0-9._-]+(\/.*)?$/i.test(query.trim())) {
      const cleanQuery = query.trim().replace(/^go\//i, "");
      const parts = cleanQuery.split("/");
      const slug = parts[0];
      const rest = parts.slice(1).join("/");
      if (slug && shortcuts[slug]) {
        const base = normalizeTargetUrl(shortcuts[slug]);
        return rest ? `${base.replace(/\/+$/, "")}/${rest}` : base;
      }
    }
  } catch {
    // Ignore non-standard URLs
  }
  return null;
}

chrome.webNavigation.onBeforeNavigate.addListener(async (details) => {
  if (details.frameId !== 0) return;

  const data = await chrome.storage.local.get(["shortcuts", "blocklist"]);
  const shortcuts = data.shortcuts || DEFAULT_SHORTCUTS;
  const blocklist = data.blocklist || DEFAULT_BLOCKLIST;

  // 1. Check for `go/<slug>` shortcut
  const targetUrl = resolveGoNavigation(details.url, shortcuts);
  if (targetUrl) {
    chrome.tabs.update(details.tabId, { url: targetUrl });
    return;
  }

  // 2. Fallback check for blocked domain
  try {
    const u = new URL(details.url);
    if (u.protocol !== "http:" && u.protocol !== "https:") return;

    const host = u.hostname.toLowerCase().replace(/^www\./, "");
    for (const domain of blocklist) {
      const clean = normalizeDomain(domain);
      if (clean && (host === clean || host.endsWith("." + clean))) {
        const blockedUrl = `${chrome.runtime.getURL("blocked.html")}?domain=${encodeURIComponent(clean)}&url=${encodeURIComponent(details.url)}`;
        chrome.tabs.update(details.tabId, { url: blockedUrl });
        return;
      }
    }
  } catch {
    // Ignore invalid URLs
  }
});

// Initialize default storage state on install
chrome.runtime.onInstalled.addListener(async () => {
  const existing = await chrome.storage.local.get([
    "shortcuts",
    "blocklist",
    "shortcutsText",
    "blocklistText",
  ]);
  const updates = {};
  if (!existing.shortcuts) updates.shortcuts = DEFAULT_SHORTCUTS;
  if (!existing.blocklist) updates.blocklist = DEFAULT_BLOCKLIST;
  if (existing.shortcutsText === undefined)
    updates.shortcutsText = DEFAULT_SHORTCUTS_TEXT;
  if (existing.blocklistText === undefined)
    updates.blocklistText = DEFAULT_BLOCKLIST_TEXT;

  if (Object.keys(updates).length > 0) {
    await chrome.storage.local.set(updates);
  }
  await syncControlPlane();
});

chrome.runtime.onStartup.addListener(() => {
  syncControlPlane();
});

chrome.storage.onChanged.addListener((changes, area) => {
  if (area === "local" && (changes.shortcuts || changes.blocklist)) {
    syncControlPlane();
  }
});

chrome.runtime.onMessage.addListener((msg, _sender, sendResponse) => {
  if (msg && msg.type === "GET_PAC_SCRIPT") {
    chrome.storage.local.get(["shortcuts", "blocklist"]).then((data) => {
      sendResponse({
        pacScript: generatePacScript(
          data.blocklist || DEFAULT_BLOCKLIST,
          data.shortcuts || DEFAULT_SHORTCUTS
        ),
      });
    });
    return true;
  }
});
